-- sys_sitemap: bảng sitemap entries per tenant (Postgres version)
CREATE TABLE IF NOT EXISTS sys_sitemap (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    loc VARCHAR(500) NOT NULL,
    freq VARCHAR(50) NOT NULL,
    priority DOUBLE NOT NULL,

    CONSTRAINT uk_sys_sitemap_tenant_loc UNIQUE (tenant_id, loc)
);

-- sys_filemap: bảng file path mapping per tenant (Postgres version)
CREATE TABLE IF NOT EXISTS sys_filemap (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    src VARCHAR(500) NOT NULL,
    dest VARCHAR(500) NOT NULL,

    CONSTRAINT uk_sys_filemap_tenant_src UNIQUE (tenant_id, src)
);

-- Auto-update updated_at trigger cho sys_sitemap
CREATE OR REPLACE TRIGGER trg_sys_sitemap_updated_at BEFORE UPDATE ON sys_sitemap
  FOR EACH ROW EXECUTE FUNCTION update_updated_at_column();

-- Auto-update updated_at trigger cho sys_filemap
CREATE OR REPLACE TRIGGER trg_sys_filemap_updated_at BEFORE UPDATE ON sys_filemap
  FOR EACH ROW EXECUTE FUNCTION update_updated_at_column();